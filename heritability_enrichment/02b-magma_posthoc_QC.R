check.file = function(prefix, suffix) {
  file.name = paste(prefix, suffix, sep=".")
  if (!file.exists(file.name)) stop(paste0("file '", file.name, "' does not exist"), call.=F)
  return(file.name)
}

strip.tag = function(var.name, tag.type=NULL) {
  tag.match = ifelse(is.null(tag.type), "[^)]*", tag.type)
  return(gsub(paste0(" *\\(", tag.match, "\\) *$"), "", var.name))
}

# parses all sets / interactions in input file, filters out any that are incompatible with specified type
load.genes.out = function(file.prefix, type=c("set", "inter-ss", "inter-sc")) {
  type = match.arg(type); is.inter = type != "set"
  file.name = check.file(file.prefix, paste("gsa", ifelse(is.inter, "inter", "sets"), "genes.out", sep="."))
  if (!exists("file.name", inherits=F)) return();
  raw = scan(file.name, what="", sep="\n", quiet=T) 

  id = suppressWarnings(as.numeric(gsub(paste0("^(# *)?_", ifelse(is.inter, "INTER", "SET"), "([0-9]*)_.*"), "\\2", raw))); used.rows = !is.na(id)
  has.param = function(name) {return(any(params[,1] == name))}
  fetch.param = function(name) {return(ifelse(has.param(name), params[min(which(params[,1] == name)),2], NA))}
  out = list()
  for (i in unique(id[used.rows])) {
    curr = raw[used.rows & id == i]
    tag = paste0(ifelse(is.inter, "INTER", "SET"), i)
    params = matrix(unlist(strsplit(gsub(paste0("^# *_", tag, "_ *"), "", grep("^#", curr, value=T)), " *= *")), byrow=T, ncol=2)

    info = list(tag = tag, name = fetch.param("VARIABLE"))
    if (has.param("MODEL")) info$model.id = as.numeric(fetch.param("MODEL"))
    info$no.genes = as.numeric(fetch.param("NGENES"))
    info$pval = as.numeric(fetch.param("P-VALUE"))
    info$genes = read.table(text=curr, header=T, stringsAsFactors=F)[,-1]

    if (is.null(dim(info$genes)) || all(dim(info$genes) == 0)) next
    if (!all(c("GENE", "ZSTAT", "ZRESID_BASE") %in% names(info$genes))) next
    if (type == "inter-ss" && !(all(c("SET1", "SET2") %in% names(info$genes)))) next
    if (type == "inter-sc") {
      if (!("COVAR" %in% names(info$genes))) next    
      info$genes$OUTLIER = F
      info$genes$COVAR_STD = as.numeric(scale(info$genes$COVAR))
      info$genes$ZRESID_STD = as.numeric(scale(info$genes$ZRESID_BASE))
      info$genes$DISTANCE = sqrt(info$genes$COVAR_STD^2 + info$genes$ZRESID_STD^2)
      info$genes = data.frame(ID=match(info$genes$GENE, info$genes$GENE[order(info$genes$DISTANCE, decreasing=T)]), info$genes, stringsAsFactors=F)
    }
    out[[tag]] = info
  }
  return(out)
}

load.data = function(file.prefix, type=c("set", "inter-ss", "inter-sc")) {
  type = match.arg(type); label = ifelse(type == "set", "set", ifelse(type == "inter-ss", "set x set interaction", "set x covar interaction"))
  file.name = check.file(file.prefix, "gsa.genes.out")
  if (!exists("file.name", inherits=F)) return();
  genes = read.table(file.name, header=T, stringsAsFactors=F)
  
  info = load.genes.out(file.prefix, type)
  if (length(info) == 0) stop(paste0("no valid ", label, "-specific info in input"), call.=F)
  if (!all(unlist(lapply(info, function(x) {x$genes$GENE})) %in% genes$GENE)) stop(paste0("genes in info input file do not fully overlap with general gene output"), call.=F)
  
  out = new.env(parent=globalenv())  
  out$type = type
  out$file.prefix = file.prefix
  out$genes = genes
  out$info = info
  return(out)
}

filter.sets = function(sets, filter, include=T) {
  if (is.null(sets) || is.null(filter)) return(sets)
  matched = filter %in% names(sets)
  if (!all(matched)) stop("following gene sets not found in input: ", paste(filter[!matched], collapse=", "), call.=F)

  matched = names(sets) %in% filter
  if (include) return(sets[which(matched)])
  else return(sets[which(!matched)])
}

