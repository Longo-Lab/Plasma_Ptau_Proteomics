parse.info = function(obj) {
  if (!exists("info", envir=obj, inherit=F)) stop("input object does not contain info variable", call.=F)
  if (length(obj$info) == 0) stop("input object is empty", call.=F)  

  data = list();  
  params = unique(unlist(lapply(obj$info, names))); params = params[params != "genes"]

  for (i in 1:length(obj$info)) {
    curr = obj$info[[i]]
    for (p in params) {
      value = ifelse(p %in% names(curr), curr[[p]], NA)
      if (p == "name" && !is.na(value)) value = strip.tag(value)
      data[[p]][i] = value
    }
  }
  data = data.frame(data, stringsAsFactors=F)
  names(data)[names(data) == "tag"] = "ID"
  return(data)
}

filter.info = function(obj, ids, include) {
  if (!exists("type", envir=obj, inherit=F)) stop("input object not recognised", call.=F)
  tags = paste0(ifelse(obj$type == "set", "SET", "INTER"), ids)
  matched = tags %in% names(obj$info)
  if (!all(matched)) stop("following IDs not found in input: ", paste(tags.id[!matched], collapse=", "), call.=F)
  
  matched = names(obj$info) %in% tags
  if (include) obj$info = obj$info[matched]
  else obj$info = obj$info[!matched]
}




qq.plot = function(sets.env, out.prefix, conf.perc, conf.perm) {
  conf.perc = round(conf.perc, 1); conf.perm = round(conf.perm)  
  if (!(exists("type", envir=sets.env, inherit=F) && sets.env$type == "set")) stop("input object must be of type 'set'", call.=F)
  if (conf.perc < 50 || conf.perc >= 100) stop("confidence band percentage must be between 50 and 100", call.=F)
  if (conf.perm < 1000) stop("number of permutations for confidence band must be at least 1000", call.=F)

  Z = sets.env$genes$ZRESID_BASE
  pdf(paste0(out.prefix, ".pdf"))    
  for (i in 1:length(sets.env$info)) {
    curr = sets.env$info[[i]]
    curr.genes = curr$genes; K = dim(curr.genes)[1]
    qq = cbind(quantile(Z, 1:K / (K+1)), sort(curr.genes$ZRESID_BASE))
    qq = cbind(qq, conf.band(sets.env, K, conf.perc, conf.perm))
    high = qq[,2] > qq[,3]; perc = round(mean(high) * 100, 1)
  
    lim = range(qq)
    title = paste0(strip.tag(curr$name), " (", curr$tag, ")\n(no. genes = ", K, ", outside ", conf.perc, "% conf. band = ", perc, "%)")
    plot(qq[,1:2], pch=19, col=c("grey", "red")[1+high], xlim=lim, ylim=lim, xlab="Expected residual Z-score", ylab="Observed residual Z-score", main=title)
    quart = round(K*c(0.25, 0.5, 0.75))
    points(qq[quart,1:2], pch=19, col="black")
    points(qq[,1], qq[,3], type="l", lwd=2, lty=2, col="black")
    abline(a=0, b=1, lwd=2, lty=3, col="black")
  }
  invisible(dev.off())
}

conf.band = function(sets.env, K, perc, nrep) {prop = perc / 100
  label = paste0("K", K, "_r", nrep, "_p", prop)
  if (!exists("conf.band", envir=sets.env, inherit=F)) sets.env$conf.band = list()
  if (!(label %in% names(sets.env$conf.band))) {
    cat("Sampling ", perc, "% confidence band (", K, " genes, ", format(nrep, scientific=F), " permutations)\n", sep="") 
    samp = matrix(0, nrow=nrep, ncol=K)
    for (i in 1:nrep) samp[i,] = sort(sample(sets.env$genes$ZRESID_BASE, K))
    sets.env$conf.band[[label]] = apply(samp, 2, quantile, prop)
  }
  return(sets.env$conf.band[[label]])
}




