process.outliers = function(sc.env, inter.id=NULL, gene.ids=NULL, mode=c("iterative", "sd.uni", "sd.multi", "manual.set", "manual.unset", "none"), cut.off=2) {
  mode = match.arg(mode); 
  if (!is.null(inter.id)) {
    if (is.numeric(inter.id)) inter.id = paste0("INTER", inter.id)
    matched = inter.id %in% names(sc.env$info)
    if (!all(matched)) stop("following interaction IDs not found in input: ", paste(inter.id[!matched], collapse=", "), call.=F)
  } else {inter.id = names(sc.env$info)}

  if (!is.null(gene.ids)) {
    if (is.null(inter.id) || length(inter.id) > 1) stop("gene IDs can only be specified if exactly one 'inter.id' value is provided", call.=F)
    if (!is.numeric(gene.ids) || any(gene.ids <= 0)) stop("gene IDs must be positive numbers", call.=F)
    gene.ids = round(gene.ids); max.id = dim(sc.env$info[[inter.id]]$genes)[1]
    if (max(gene.ids) > max.id) stop(paste0("gene IDs are out of range (max. value is ", max.id, ")"), call.=F)
  }
   
  for (id in inter.id) {
    genes = sc.env$info[[id]]$genes
    if (mode == "none") sc.env$info[[id]]$genes$OUTLIER = F
    else if (mode == "sd.uni") sc.env$info[[id]]$genes$OUTLIER = apply(abs(genes[,c("COVAR_STD", "ZRESID_STD")]) > cut.off, 1, any)
    else if (mode == "sd.multi") sc.env$info[[id]]$genes$OUTLIER = genes$DISTANCE > cut.off
    else if (mode == "iterative") sc.env$info[[id]]$genes$OUTLIER = iterative.outliers(genes, cut.off)
    else if (mode == "manual.set" || mode == "manual.unset") sc.env$info[[id]]$genes$OUTLIER[genes$ID %in% unique(gene.ids)] = (mode == "manual.set")
  }
} 

iterative.outliers = function(genes, cut.off) {
  values = genes[order(genes$DISTANCE),c("GENE", "COVAR_STD", "ZRESID_STD", "DISTANCE")]
  check = which(values$DISTANCE > cut.off); outliers = c()
  if (length(check) > 0) {
    for (i in check) {
      dist = sqrt(apply(sweep(values[,2:3], 2, as.numeric(values[i,2:3]), FUN="-")^2, 1, sum))
      neighbour = which.min(dist[1:(i-1)])
      if (dist[neighbour] > cut.off || neighbour %in% outliers) outliers = c(outliers, i)
    }
  }
  return(genes$GENE %in% values$GENE[outliers])
}

filter.outliers = function(sc, file.prefix, include.orig) {
  sets = list(); pairs = NULL
  for (i in 1:length(sc$info)) {
    curr = sc$info[[i]]
    if (any(curr$genes$OUTLIER) && any(!curr$genes$OUTLIER)) {
      set.name = strsplit(curr$name, " *-X- *")[[1]][1]
      cov.name = strsplit(strip.tag(curr$name), " *-X- *")[[1]][2]      
      inter.name = paste0(set.name, "#", cov.name, "#FILTERED")
      if (include.orig) {
        if (set.name %in% sets) {
          if (length(sets[[set.name]]) != dim(curr$genes)[1] || !all(sort(sets[[set.name]]) == sort(curr$genes$GENE))) stop(paste0("set name '", set.name, "' occurs multiple times, containing different genes", call.=F))
        } else sets[[set.name]] = curr$genes$GENE
        pairs = rbind(pairs, c(set.name, cov.name))
      }
      sets[[inter.name]] = curr$genes$GENE[!curr$genes$OUTLIER]
      pairs = rbind(pairs, c(inter.name, cov.name))
    }
  }
  if (length(sets) == 0) stop("no sets in input containing any outliers", call.=F)  

  write.table(pairs, file=paste0(file.prefix, ".sc-outliers.models"), row.names=F, col.names=F, quote=F, sep="\t")
  return(sets)
}

create.partitions = function(sc, file.prefix, num.part, min.size) {
  num.part = round(num.part); min.size = round(min.size)
  if (num.part < 2 || num.part > 10) stop("number of partitions must be between 2 and 10")  
  if (min.size < 5) stop("minimum partition size must be at least 5")  
  min.set.size = min.size * num.part
  
  sets = list(); models = list()
  for (i in 1:length(sc$info)) {
    curr = sc$info[[i]] 
    curr.genes = curr$genes[order(curr$genes$COVAR),]
    K = dim(curr.genes)[1]

    if (K >= min.set.size) {
      set.name = strsplit(curr$name, " *-X- *")[[1]][1]
      cov.name = strsplit(strip.tag(curr$name), " *-X- *")[[1]][2]      
      part.names = paste0(set.name, "#", cov.name, "#PART", 1:num.part)
      partitions = sort(rep(1:num.part, length.out=K))
      
      if (set.name %in% sets) {
        if (length(sets[[set.name]]) != K || !all(sort(sets[[set.name]]) == sort(curr.genes$GENE))) stop(paste0("set name '", set.name, "' occurs multiple times, containing different genes", call.=F))
      } else sets[[set.name]] = curr.genes$GENE
      
      for (p in 1:num.part) {
        sets[[part.names[p]]] = curr.genes$GENE[partitions == p] 
        models[[length(models)+1]] = part.names[p]
        models[[length(models)+1]] = c(part.names[p], set.name)
      }
    } else cat("skipping ", strip.tag(curr$name), " (", curr$tag, "), partitions are too small\n", sep="")
  }
  if (length(sets) == 0) stop("no sets in input passed minimum partition size", call.=F)  
  
  write.table(unlist(lapply(models, paste, collapse=" ")), file=paste0(file.prefix, ".sc-partition.models"), row.names=F, col.names=F, quote=F, sep="\t")
  return(sets)
}

