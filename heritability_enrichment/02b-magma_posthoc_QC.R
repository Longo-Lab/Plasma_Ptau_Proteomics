# data loading functions for gene set main effect and set x set (load.ss) / set x covar (load.sc) interactions
# load files [PREFIX].gsa.genes.out and [PREFIX].gsa.sets.genes.out / [PREFIX].gsa.inter.genes.out and validates content
# output a results object containing the (primary) variables:
# - genes: data frame with gene output for all genes in analysis, loaded from file [PREFIX].gsa.genes.out
# - info: list of lists with info for each gene set / interaction loaded from [PREFIX].gsa.sets.genes.out / [PREFIX].gsa.inter.genes.out
#         per gene set / interaction, contains basic parameters and gene output for all genes it contains
#         NB: for set x set interactions, contains gene output for all genes in at least one of the sets
# note: the output is an R environment object and can be accessed in the standard ways (eg. names(obj) lists internal variables, obj$info accesses the info variable, etc.)

load.sets = function(file.prefix) {return(load.data(file.prefix, "set"))}
load.ss = function(file.prefix) {return(load.data(file.prefix, "inter-ss"))}
load.sc = function(file.prefix) {return(load.data(file.prefix, "inter-sc"))}



# shows a summary of the results (show.info) in the object generated by the above functions 
show.info = function(obj) {parse.info(obj)}

# filter entries from the results object based on their IDs (can be a vector); this is the numeric part of the IDs listed using show.info()
filter.results = function(obj, ids, mode=c("keep", "drop")) {filter.info(obj, ids, match.arg(mode) == "keep")}



# read a set definition file into a list (name of each entry is the gene-set name, content is a vector of gene IDs)
# assumes standard MAGMA row-based input format unless by.row is set to false; col.ids specifies columns to use in that case, first value for set ID column, second value for gene ID column
# filter takes an optional vector of gene-set names to retain from the file, discarding the rest
read.setfile = function(file.name, filter=NULL, by.row=T, col.ids=c(1,2)) {
  if (by.row) return(filter.sets(sets.rows(file.name), filter))
  else return(filter.sets(sets.cols(file.name, col.ids), filter))
}

# note: the filter.sets(sets, filter, include=T) function can also be used on its own later, on an output list created by read.setfile()
# with include=T, only the gene sets in the 'filter' vector are retained; with include=F, only the gene sets not in that vector are retained



# QQ-plot function for gene set associations, use with load.sets(); out.prefix is the prefix of the created PDF file
# conf.perc and conf.perm are the percentage of the confidence band, and number of permutations used to create it
plot.sets = function(sets, out.prefix, conf.perc=95, conf.perm=100000) {qq.plot(sets, out.prefix, conf.perc, conf.perm)}



# scatter plot function for set by covariate interactions, use with load.sc(); out.prefix is the prefix of the created PDF file
# with show.ids=T, the plot points are replaced with the internal IDs for the genes (for use with manual outlier marking functions)
plot.sc = function(sc, out.prefix, show.ids=F) {scatter.plot(sc, out.prefix, show.ids)}

# basic outlier specification function; sets outliers according to selected mode and distance value (see accompanying manual for details), "none" removes all outlier marking
# inter.id is a numeric value / vector specifying which entries to apply it to (IDs are the numeric component of INTER1, INTER2, etc.); applied to all entries if null
outliers = function(sc, inter.id=NULL, mode=c("iterative", "sd.uni", "sd.multi", "none"), distance=2) {process.outliers(sc, inter.id, mode=match.arg(mode), cut.off=distance)}

# functions to manually mark/unmark genes as outliers; inter.id is a single numeric ID, gene.ids can be a vector (IDs are as shown in scatter plots with show.ids=T, or in ID column in sc$info[[inter.id]]$genes
mark.outliers = function(sc, inter.id, gene.ids) {process.outliers(sc, inter.id, gene.ids=gene.ids, mode="manual.set")}
unmark.outliers = function(sc, inter.id, gene.ids) {process.outliers(sc, inter.id, gene.ids=gene.ids, mode="manual.unset")}



# function to create .sets file containing set definitions with outliers dropped, plus a .models file for use with --model interactions option (only for interactions with marked outliers)
# with include.orig=T, the full original gene set is also included in the .sets file; include.sets can be used to add additional gene sets to the .sets file (in format as per read.setfile)
outlier.sets = function(sc, file.prefix, include.orig=T, include.sets=NULL) {write.sets(filter.outliers(sc, file.prefix, include.orig), paste0(file.prefix, ".outlier"), include.sets)}

# function to create .sets file containing partitioned gene sets for interactions in the input, plus a .models file for use with --model joint option
# num.part sets the number of partitions to use, min.size the minimum size of partitions (interactions with smaller partitions are skipped)
# include.sets can be used to add additional gene sets to the .sets file (in format as per read.setfile)
partitioned.sets = function(sc, file.prefix, num.part=4, min.size=10, include.sets=NULL) {write.sets(create.partitions(sc, file.prefix, num.part, min.size), paste0(file.prefix, ".partitioned"), include.sets)}




