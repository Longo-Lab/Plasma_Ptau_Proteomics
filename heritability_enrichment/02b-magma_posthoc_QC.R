write.sets = function(sets, file.prefix, include.sets) {
  if (is.null(sets)) return()
  if (length(sets) == 0) stop("list of sets is empty")
  if (!is.null(include.sets)) sets = c(sets, include.sets[which(!names(include.sets) %in% names(sets))])
  
  out.file = paste0(file.prefix, ".sets")
  set.names = names(sets)
